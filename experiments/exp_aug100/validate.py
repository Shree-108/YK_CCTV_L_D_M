"""Integrity checks that must pass before any run, then write the scene-split path lists and data YAMLs.

    python -m experiments.exp_aug100.validate
"""
from __future__ import annotations

import json
import os

from experiments.exp_aug100.common import (ANN, DS, EXP, IMG_DIR, LBL_DIR, SCENES, check_v3, fname, read_manifest,
                                           sha256)

# Portable layout (no machine-specific paths): the path lists sit in the dataset folder with entries
# "./images/train/<file>" (Ultralytics resolves "./" against the list file's folder), and each data YAML has no
# "path" key, so its train/val entries resolve against the YAML's own folder.
REL_DS = os.path.relpath(DS, EXP).replace(os.sep, "/")               # "../../dataset/exp_aug100"
FOLDS = {"AtoB": ("A_shopfront", "B_roadside_bin"), "BtoA": ("B_roadside_bin", "A_shopfront")}


def main() -> int:
    check_v3()
    errs, n_boxes, sizes = [], 0, []
    rows = read_manifest()
    if len(rows) != 100: errs.append(f"manifest has {len(rows)} rows, expected 100")
    imgs = {p.stem for p in IMG_DIR.glob("*.jpg")}; lbls = {p.stem for p in LBL_DIR.glob("*.txt")}
    if imgs != lbls: errs.append(f"image/label mismatch: {sorted(imgs ^ lbls)[:5]}")
    for r in rows:
        if r["label_status"] not in ("verified", "manual_verified"): errs.append(f"{r['file']}: label_status {r['label_status']}")
        if sha256(IMG_DIR / r["file"]) != r["sha256"]: errs.append(f"{r['file']}: copy hash differs from original")
        if r["scene"] != ("A_shopfront" if int(r["file"][12:15]) % 2 else "B_roadside_bin"): errs.append(f"{r['file']}: scene")
        lines = [l.split() for l in (LBL_DIR / (r["file"][:-4] + ".txt")).read_text().splitlines() if l.strip()]
        seen = []
        for l in lines:
            if len(l) != 5 or l[0] != "0": errs.append(f"{r['file']}: bad line {l}"); continue
            x, y, w, h = map(float, l[1:])
            if not (0 < x < 1 and 0 < y < 1 and 0 < w <= 1 and 0 < h <= 1): errs.append(f"{r['file']}: coords {l}")
            if w * 1280 < 2 or h * 720 < 2: errs.append(f"{r['file']}: box < 2 px")
            for s in seen:
                ix = max(0, min(x + w / 2, s[0] + s[2] / 2) - max(x - w / 2, s[0] - s[2] / 2))
                iy = max(0, min(y + h / 2, s[1] + s[3] / 2) - max(y - h / 2, s[1] - s[3] / 2))
                if ix * iy / (w * h + s[2] * s[3] - ix * iy) > 0.9: errs.append(f"{r['file']}: duplicate box")
            seen.append((x, y, w, h)); sizes.append(min(w * 1280, h * 720))
        if int(r["n_boxes"]) != len(lines): errs.append(f"{r['file']}: n_boxes {r['n_boxes']} != {len(lines)}")
        n_boxes += len(lines)
    rel_img = IMG_DIR.relative_to(DS).as_posix()                    # "images/train"
    for fold, (tr, va) in FOLDS.items():
        trs = [f"./{rel_img}/{fname(n)}" for n in SCENES[tr]["ids"]]
        vas = [f"./{rel_img}/{fname(n)}" for n in SCENES[va]["ids"]]
        if set(trs) & set(vas): errs.append(f"{fold}: train/val overlap")
        if {r["scene"] for r in rows if f"./{rel_img}/{r['file']}" in trs} != {tr}: errs.append(f"{fold}: train scene leak")
        if not all((DS / p).is_file() for p in trs + vas): errs.append(f"{fold}: path list entry does not resolve")
        for split, lst in (("train", trs), ("val", vas)):
            (DS / f"{fold}_{split}.txt").write_text("\n".join(lst) + "\n", encoding="utf-8", newline="\n")
        (EXP / f"data_{fold}.yaml").write_text(
            f"# AUG100 scene-transfer fold {fold}: train = {tr}, val = {va}. Generated by validate.py.\n"
            f"# Exploratory only: 2 synthetic scenes. NOT a measure of real CCTV accuracy.\n"
            f"# Project-relative: no 'path' key, so Ultralytics resolves train/val against this file's folder.\n"
            f"train: {REL_DS}/{fold}_train.txt\nval: {REL_DS}/{fold}_val.txt\n"
            f"names:\n  0: litter\n", encoding="utf-8", newline="\n")
    small = sum(s < 16 for s in sizes); mid = sum(16 <= s < 32 for s in sizes)
    report = {"images": len(rows), "boxes": n_boxes, "class": {"litter": n_boxes},
              "boxes_by_min_side": {"<16px": small, "16-32px": mid, ">=32px": len(sizes) - small - mid},
              "per_scene": {s: sum(int(r["n_boxes"]) for r in rows if r["scene"] == s) for s in SCENES},
              "errors": errs}
    (ANN / "validation.json").write_text(json.dumps(report, indent=1))
    print(json.dumps({k: v for k, v in report.items() if k != "errors"}))
    print("ERRORS:" if errs else "VALID: all checks passed", *errs[:20], sep="\n  ")
    check_v3()
    return 1 if errs else 0


if __name__ == "__main__":
    raise SystemExit(main())
